//! Read-only public projections. No runtime ownership or command execution lives here.
use crate::preferences::Passage;
use crate::{
    audio, document, preferences,
    sound_runtime, startup, state_order,
};
use panthesia_core::practice::{AttemptSummary, PracticeSnapshot};
use serde::Serialize;
use std::path::PathBuf;

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Note {
    pub pitch: u8,
    pub start: f64,
    pub duration: f64,
    pub velocity: u8,
    pub track: usize,
    pub tick: f64,
    pub end_tick: f64,
    pub finger: Option<u8>,
    pub index: usize,
    pub part: String,
    pub manual_hand: bool,
    pub playback_mode: panthesia_core::song_config::PlayerConfig,
}
#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct LoadedSong {
    pub title: String,
    pub content_id: String,
    pub source_path: PathBuf,
    pub duration: f64,
    pub notes: Vec<Note>,
    pub measures: Vec<document::Bar>,
    pub tempo: Vec<document::Tempo>,
    pub ppq: u16,
    pub tracks: Vec<document::Track>,
    pub generated: bool,
    pub has_score: bool,
    pub score_revision: u64,
    pub meter_correction: Option<panthesia_core::library::MeterCorrection>,
}
#[derive(Clone, Default, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PlaybackPerformance {
    pub max_gap_ms: f64,
    pub late_ticks: u64,
    pub max_tick_ms: f64,
    pub max_publish_ms: f64,
}
#[derive(Clone, Serialize)]
pub struct LiveKey { pub velocity:u8, pub serial:u64 }

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Snapshot {
    pub playback_performance: PlaybackPerformance,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub state_order: Option<state_order::StateOrder>,
    pub music_import_version: u8,
    pub exercise_generation_version: u8,
    pub package_import_version: u8,
    pub startup: startup::Status,
    pub recording_unsaved: bool,
    pub recording_path: Option<PathBuf>,
    pub storage: crate::storage_status::Status,
    pub content_id: Option<String>,
    pub score_revision: u64,
    pub annotation_revision: u64,
    pub status: String,
    pub position: f64,
    pub duration: f64,
    pub practice_ms: u64,
    pub speed: f64,
    pub wait: bool,
    pub hands: String,
    pub required: Vec<u8>,
    pub pressed: Vec<u8>,
    pub pressed_keys: std::collections::BTreeMap<u8,LiveKey>,
    pub score: PracticeSnapshot,
    pub input: Option<String>,
    pub output: String,
    pub output_id: Option<String>,
    pub soundfont: PathBuf,
    pub soundfont_status: String,
    pub sound: sound_runtime::Status,
    pub audio_level: Option<f32>,
    pub audio_performance: Option<audio::Performance>,
    pub soundfont_warning: Option<String>,
    pub error: Option<String>,
    pub saved: bool,
    pub current_history_id: Option<String>,
    pub passage: Option<Passage>,
    pub repetitions: usize,
    pub volume: f64,
    pub mode: String,
    pub measure: usize,
    pub beat: f64,
    pub tick: f64,
    pub bpm: f64,
    pub count_in: u8,
    pub count_remaining: f64,
    pub metronome: bool,
    pub latency: i32,
    pub summary: Option<preferences::Shared<AttemptSummary>>,
    pub summary_version: String,
    pub recording: bool,
    pub record_duration: f64,
    pub input_connected: bool,
    pub midi_events: u64,
    pub note_epoch: u64,
    pub pedal: u8,
    pub rounds: usize,
}
