export interface LocatedPaperNote {
  track: number;
  index: number;
  pitch: number;
  measure: number;
  page: number;
  rendererId: string;
  region: PaperRegion;
}

export interface LocatedPaperPlan {
  notes: LocatedPaperNote[];
  skipped: number;
  reasons: string[];
}

function regionFor(inverse: DOMMatrix, box: DOMRect, element: SVGGraphicsElement): PaperRegion | null {
  const rect = (element.querySelector(".notehead") as SVGGraphicsElement | null ?? element).getBoundingClientRect();
  if (rect.width <= 0 || rect.height <= 0) return null;
  const first = new DOMPoint(rect.left, rect.top).matrixTransform(inverse);
  const last = new DOMPoint(rect.right, rect.bottom).matrixTransform(inverse);
  const left = Math.min(first.x, last.x), right = Math.max(first.x, last.x);
  const top = Math.min(first.y, last.y), bottom = Math.max(first.y, last.y);
  const x = Math.max(0, (left - box.x) / box.width - 0.004);
  const y = Math.max(0, (top - box.y) / box.height - 0.003);
  const endX = Math.min(1, (right - box.x) / box.width + 0.004);
  const endY = Math.min(1, (bottom - box.y) / box.height + 0.003);
  if (![x, y, endX, endY].every(Number.isFinite) || endX - x < 0.002 || endY - y < 0.002)
    return null;
  return { x, y, width: endX - x, height: endY - y };
}

export function locatedPaperMeasureAt(song: Pick<LoadedSong, "measures">, seconds: number): number | null {
  let low = 0, high = song.measures.length;
  while (low < high) {
    const middle = (low + high) >>> 1;
    if (seconds >= song.measures[middle].start - 0.001) low = middle + 1; else high = middle;
  }
  const index = low - 1, measure = song.measures[index];
  return measure && (seconds < measure.end - 0.001 || index === song.measures.length - 1 && seconds <= measure.end + 0.001) ? index + 1 : null;
}
function check(signal?: AbortSignal) { if (signal?.aborted) throw new DOMException("谱页处理已停止，当前输入保留。", "AbortError"); }
async function abortable<T>(work: Promise<T>, signal?: AbortSignal): Promise<T> {
  check(signal);
  if (!signal) return work;
  let stopped: () => void = () => {};
  const cancelled = new Promise<never>((_, reject) => {
    stopped = () => reject(new DOMException("谱页处理已停止，当前输入保留。", "AbortError"));
    signal.addEventListener("abort", stopped, { once: true });
  });
  try { return await Promise.race([work, cancelled]); }
  finally { signal.removeEventListener("abort", stopped); }
}
function yieldToInterface() {
  return new Promise<void>((resolve) => {
    const channel = new MessageChannel();
    channel.port1.onmessage = () => { channel.port1.close(); channel.port2.close(); resolve(); };
    channel.port2.postMessage(null);
  });
}
/** Measure only the SVG generated by the current, correlated MusicXML source. */
function* planSteps(
  count: number, mapping: ScoreMapping[], song: LoadedSong,
): Generator<{ page: number; total: number; load?:number }, LocatedPaperPlan, string | undefined> {
  if (!count || count > 80) throw new Error("可定位谱需有 1 至 80 页。");
  const noteByIdentity = new Map<string, LoadedSong["notes"][number] | null>();
  for (const note of song.notes) {
    const key = `${note.track}:${note.index}`;
    noteByIdentity.set(key, noteByIdentity.has(key) ? null : note);
  }
  const mapped = new Map<string, ScoreMapping[]>();
  for (const item of mapping) {
    const key = `${item.track}:${item.index}`;
    const old = mapped.get(key) ?? [];
    old.push(item);
    mapped.set(key, old);
  }
  const regions = new Map<string, PaperRegion>(), seen = new Set<string>(), ambiguous = new Set<string>();
  const host = document.createElement("div");
  host.style.cssText = "position:fixed;left:-10000px;top:0;width:1050px;visibility:hidden;pointer-events:none;";
  document.body.append(host);
  try {
    for (let index = 0; index < count; index++) {
      host.innerHTML = (yield {page:index+1,total:count,load:index}) ?? "";
      const svg = host.querySelector("svg") as SVGSVGElement | null;
      if (!svg) continue;
      svg.style.width = "1050px";
      svg.style.height = "auto";
      const matrix = svg.getScreenCTM(), box = svg.viewBox.baseVal;
      if (!matrix || box.width <= 0 || box.height <= 0) continue;
      const inverse = matrix.inverse();
      let processed = 0;
      for (const element of svg.querySelectorAll<SVGGraphicsElement>("g.note[id]")) {
        const key = `${index}:${element.id}`;
        if (seen.has(key)) { ambiguous.add(key); regions.delete(key); }
        else {
          seen.add(key);
          const region = regionFor(inverse, box, element);
          if (region) regions.set(key, region);
        }
        if (++processed % 256 === 0) yield { page: index + 1, total: count };
      }
      yield { page: index + 1, total: count };
    }
  } finally {
    host.remove();
  }
  const notes: LocatedPaperNote[] = [];
  const issues = new Map<string, number>();
  for (const [key, note] of noteByIdentity) {
    if (!note) { issues.set("参考音身份重复", (issues.get("参考音身份重复") ?? 0) + 1); continue; }
    const candidates = mapped.get(key) ?? [];
    const unique = new Map(candidates.map((item) => [`${item.page}:${item.id}`, item]));
    if (unique.size !== 1) {
      issues.set("谱音对应不唯一或未配对", (issues.get("谱音对应不唯一或未配对") ?? 0) + 1);
      continue;
    }
    const item = [...unique.values()][0];
    if (ambiguous.has(`${item.page}:${item.id}`)) { issues.set("谱页音符标识重复", (issues.get("谱页音符标识重复") ?? 0) + 1); continue; }
    const region = regions.get(`${item.page}:${item.id}`);
    const measure = locatedPaperMeasureAt(song, note.start);
    if (!region || item.pitch !== note.pitch || measure === null) {
      issues.set("谱音位置或小节无法核对", (issues.get("谱音位置或小节无法核对") ?? 0) + 1);
      continue;
    }
    notes.push({ track: note.track, index: note.index, pitch: note.pitch, measure, page: item.page + 1, rendererId: item.id, region });
  }
  return {
    notes,
    skipped: noteByIdentity.size - notes.length,
    reasons: [...issues].map(([name, count]) => `${name} ${count} 处`),
  };
}

/** Synchronous entry remains available for callers that already schedule their own work. */
export function buildLocatedPaperPlan(pages: string[], mapping: ScoreMapping[], song: LoadedSong): LocatedPaperPlan {
  const work = planSteps(pages.length, mapping, song);
  let source:string|undefined;
  for (;;) { const next = work.next(source);source=undefined;if (next.done) return next.value;if(next.value.load!==undefined)source=pages[next.value.load]; }
}
export async function buildLocatedPaperPlanAsync(
  pages: string[] | ScorePages, mapping: ScoreMapping[], song: LoadedSong,
  options: { signal?: AbortSignal; progress?: (page: number, total: number) => void } = {},
): Promise<LocatedPaperPlan> {
  const work = planSteps(pages.length, mapping, song);
  try {
    let source:string|undefined;
    for (;;) {
      check(options.signal);
      const next = work.next(source);source=undefined;
      if (next.done) return next.value;
      if(next.value.load!==undefined)source=Array.isArray(pages)?pages[next.value.load]:await pages.get(next.value.load,options.signal);
      options.progress?.(next.value.page, next.value.total);
      await yieldToInterface();
    }
  } finally { work.return({ notes: [], skipped: 0, reasons: [] }); }
}

export async function svgPagePng(source: string, signal?: AbortSignal): Promise<Blob> {
  check(signal);
  const parsed = new DOMParser().parseFromString(source, "image/svg+xml");
  const svg = parsed.documentElement as unknown as SVGSVGElement;
  if (svg.localName !== "svg" || !svg.viewBox) throw new Error("谱页 SVG 内容无法完整读取");
  const box = svg.viewBox.baseVal;
  if (![box.width, box.height].every(Number.isFinite) || box.width <= 0 || box.height <= 0) throw new Error("谱页尺寸无效");
  const width = 1100, height = Math.ceil(width * box.height / box.width);
  if (height > 4200) throw new Error("谱页高度超出可生成范围");
  svg.setAttribute("width", String(width));
  svg.setAttribute("height", String(height));
  const url = URL.createObjectURL(new Blob([new XMLSerializer().serializeToString(svg)], { type: "image/svg+xml" }));
  const image = new Image(), canvas = window.document.createElement("canvas");
  try {
    image.src = url;
    await abortable(image.decode(), signal);
    check(signal);
    canvas.width = width; canvas.height = height;
    const context = canvas.getContext("2d");
    if (!context) throw new Error("无法创建谱页画布");
    context.fillStyle = "#ffffff";
    context.fillRect(0, 0, width, height);
    context.drawImage(image, 0, 0, width, height);
    const blob = await abortable(new Promise<Blob | null>((resolve) => canvas.toBlob(resolve, "image/png")), signal);
    check(signal);
    if (!blob) throw new Error("谱页图片生成失败");
    return blob;
  } finally {
    image.src = ""; canvas.width = 0; canvas.height = 0;
    URL.revokeObjectURL(url);
  }
}
